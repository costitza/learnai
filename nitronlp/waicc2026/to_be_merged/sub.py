def probs9_to_probs3(p9):
    return np.column_stack([p9[:, 0], p9[:, 1:6].sum(axis=1), p9[:, 6:9].sum(axis=1)])

def macro_f1(y, p, k):
    cm = np.bincount(y * k + p, minlength=k * k).reshape(k, k)
    tp = np.diag(cm); fp = cm.sum(0) - tp; fn = cm.sum(1) - tp
    present = (cm.sum(0) + cm.sum(1)) > 0
    f1 = np.where(2 * tp + fp + fn > 0, 2 * tp / np.maximum(2 * tp + fp + fn, 1), 0.0)
    return f1[present].mean()

def joint(p9, p3, y3_t, y9_t):
    s1 = macro_f1(y3_t, p3.argmax(1), 3)
    s2 = macro_f1(y9_t, p9.argmax(1), 9)
    return s1, s2, 0.5 * (s1 + s2)

GRID = np.linspace(0.5, 2.5, 41)

def coord_search(P, score_fn, rounds=3):
    w = np.ones(P.shape[1]); best = score_fn(P)
    for _ in range(rounds):
        improved = False
        for c in range(P.shape[1]):
            for m in GRID:
                if m == w[c]:
                    continue
                wt = w.copy(); wt[c] = m
                s = score_fn(P * wt)
                if s > best + 1e-5:
                    best, w, improved = s, wt, True
        if not improved:
            break
    return w

