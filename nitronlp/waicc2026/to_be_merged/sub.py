def head_tail_words(text, head_w, tail_w):
    words = clean_ro(text).split()
    if len(words) <= head_w + tail_w:
        return " ".join(words)
    return " ".join(words[:head_w]) + " [...] " + " ".join(words[-tail_w:])

def format_pair(row):
    q_text = f"[{row['president']} | {row['context']}] Întrebare: {head_tail_words(row['interview_question'], 70, 40)}"
    ctx = []
    if row['prev_q']:
        ctx.append("Întrebare anterioară: " + " ".join(row['prev_q'].split()[-25:]))
    if row['prev_a']:
        ctx.append("Răspuns anterior: " + " ".join(row['prev_a'].split()[:20]))
    if row['next_q']:
        ctx.append("Întrebare următoare: " + " ".join(row['next_q'].split()[:20]))
    if ctx:
        q_text += " || Context: " + " | ".join(ctx)
    return q_text, f"Răspuns: {clean_ro(row['interview_answer'])}"

