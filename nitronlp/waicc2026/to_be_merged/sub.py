def predict(model, loader):
    model.eval()
    p9, p3 = [], []
    with torch.no_grad():
        for batch in loader:
            with torch.amp.autocast('cuda', dtype=torch.float16, enabled=torch.cuda.is_available()):
                l9, l3 = model(batch['input_ids'], batch['attention_mask'], batch['chunk_map'], batch['n'])
            p9.append(F.softmax(l9.float(), -1).cpu().numpy())
            p3.append(F.softmax(l3.float(), -1).cpu().numpy())
    return np.vstack(p9), np.vstack(p3)

def train_fold(fold, gpu):
    device = torch.device(f'cuda:{gpu}' if torch.cuda.is_available() else 'cpu')
    if torch.cuda.is_available():
        torch.cuda.set_device(device)
    torch.manual_seed(CFG.SEED + fold)
    log = lambda s: print(f'[GPU{gpu} | Fold {fold}] {s}', flush=True)

    tr_mask = folds != fold
    tr_df = train_sorted[tr_mask].copy().reset_index(drop=True)
    tr_df['sample_weight'] = 1.0
    tr_df = tr_df[['text_q', 'text_a', 'clarity_label', 'evasion_label', 'sample_weight']]
    if extra_df is not None:
        tr_df = pd.concat([tr_df, extra_df], ignore_index=True)
    va_df = train_sorted[~tr_mask].reset_index(drop=True)
    va_idx = np.where(~tr_mask)[0]
    tr_chunks = [c for c, m in zip(ro_chunks, tr_mask) if m] + extra_chunks
    va_chunks = [c for c, m in zip(ro_chunks, tr_mask) if not m]
    tr_loader = DataLoader(PolERoDataset(tr_df, True, tr_chunks), batch_size=CFG.BATCH_SIZE, shuffle=True, collate_fn=collate_fn)
    va_loader = DataLoader(PolERoDataset(va_df, True, va_chunks), batch_size=CFG.BATCH_SIZE * 2, collate_fn=collate_fn)
    te_loader = DataLoader(test_ds, batch_size=CFG.BATCH_SIZE * 2, collate_fn=collate_fn)

    model = EvasionClassifier(CFG.MODEL_NAME, device)
    if CFG.OPTIMIZER == 'adamw':
        optimizer = torch.optim.AdamW(param_groups(model), lr=CFG.LR)
    else:
        optimizer = Adafactor(param_groups(model), lr=CFG.LR, scale_parameter=False, relative_step=False, warmup_init=False)
    total_steps = math.ceil(len(tr_loader) / CFG.GRAD_ACCUM) * CFG.EPOCHS
    scheduler = get_cosine_schedule_with_warmup(optimizer, int(0.1 * total_steps), total_steps)
    ce = nn.CrossEntropyLoss(reduction='none')
    scaler = torch.amp.GradScaler('cuda', enabled=torch.cuda.is_available())

    best_score, best_va, best_state, bad = -1.0, None, None, 0
    for epoch in range(CFG.EPOCHS):
        model.train()
        optimizer.zero_grad(set_to_none=True)
        run_loss = 0.0
        for step, batch in enumerate(tr_loader):
            y9, y3, sw = batch['y9'].to(device), batch['y3'].to(device), batch['sw'].to(device)
            with torch.amp.autocast('cuda', dtype=torch.float16, enabled=torch.cuda.is_available()):
                l9, l3 = model(batch['input_ids'], batch['attention_mask'], batch['chunk_map'], batch['n'])
            loss = ((ce(l9.float(), y9) * sw).mean() + CFG.AUX3_WEIGHT * (ce(l3.float(), y3) * sw).mean()) / CFG.GRAD_ACCUM
            run_loss += loss.item() * CFG.GRAD_ACCUM
            scaler.scale(loss).backward()
            if (step + 1) % CFG.GRAD_ACCUM == 0 or step + 1 == len(tr_loader):
                scaler.unscale_(optimizer)
                torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
                scaler.step(optimizer); scaler.update(); scheduler.step()
                optimizer.zero_grad(set_to_none=True)
            if step % 100 == 0:
                log(f'Ep {epoch+1} step {step}/{len(tr_loader)} loss {run_loss / (step + 1):.4f}')

        va_p9, va_p3d = predict(model, va_loader)
        va_p3 = 0.5 * np.column_stack([va_p9[:, 0], va_p9[:, 1:6].sum(1), va_p9[:, 6:].sum(1)]) + 0.5 * va_p3d
        f1_9 = f1_score(y9_all[va_idx], va_p9.argmax(1), average='macro')
        f1_3 = f1_score(y3_all[va_idx], va_p3.argmax(1), average='macro')
        score = 0.5 * (f1_9 + f1_3)
        log(f'Ep {epoch+1} | Clarity {f1_3:.4f} | Evasion {f1_9:.4f} | Mean {score:.4f}')
        if score > best_score:
            best_score, best_va, bad = score, (va_p9, va_p3d), 0
            best_state = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}
        else:
            bad += 1
            if bad >= CFG.PATIENCE:
                log(f'Early stop at epoch {epoch+1}')
                break

    model.load_state_dict(best_state)
    te_p9, te_p3 = predict(model, te_loader)
    del model, optimizer, scheduler, scaler, best_state
    gc.collect(); torch.cuda.empty_cache()
    return va_idx, best_va, te_p9, te_p3, best_score

def run_gpu(gpu):
    for fold in range(gpu, CFG.N_SPLITS, N_GPUS):
        if fold in done_folds:
            continue
        va_idx, (vp9, vp3), tp9, tp3, sc = train_fold(fold, gpu)
        with save_lock:
            oof_nn_probs9[va_idx], oof_nn_probs3[va_idx] = vp9, vp3
            test_nn_probs9[:] += tp9 / CFG.N_SPLITS
            test_nn_probs3[:] += tp3 / CFG.N_SPLITS
            done_folds.append(fold)
            k = len(done_folds)
            np.save(f'oof_{TAG}.npy', oof_nn_probs9); np.save(f'oof3_{TAG}.npy', oof_nn_probs3)
            np.save(f'test_{TAG}.npy', test_nn_probs9 * CFG.N_SPLITS / k)
            np.save(f'test3_{TAG}.npy', test_nn_probs3 * CFG.N_SPLITS / k)
            print(f'*** Fold {fold} done (best mean {sc:.4f}) | finished: {sorted(done_folds)} ***', flush=True)

with ThreadPoolExecutor(max_workers=N_GPUS) as ex:
    for f in [ex.submit(run_gpu, g) for g in range(N_GPUS)]:
        f.result()
print(f'All folds done: {sorted(done_folds)}')

