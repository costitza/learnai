def find_sub(seq, sub, start=0):
    for i in range(start, len(seq) - len(sub) + 1):
        if seq[i:i + len(sub)] == sub:
            return i
    raise ValueError("probe tokens not found")

_a = tokenizer.encode("salut", add_special_tokens=False)
_b = tokenizer.encode("lume", add_special_tokens=False)
_pair = tokenizer("salut", "lume", add_special_tokens=True)['input_ids']
_i = find_sub(_pair, _a)
_j = find_sub(_pair, _b, _i + len(_a))
PAIR_PRE, PAIR_MID, PAIR_POST = _pair[:_i], _pair[_i + len(_a):_j], _pair[_j + len(_b):]
N_SPECIAL = len(PAIR_PRE) + len(PAIR_MID) + len(PAIR_POST)

def window_starts(n, win, stride):
    if n <= win:
        return [0]
    starts = list(range(0, n - win, stride)) + [n - win]
    if len(starts) > CFG.MAX_CHUNKS:
        pick = np.linspace(0, len(starts) - 1, CFG.MAX_CHUNKS).round().astype(int)
        starts = [starts[i] for i in sorted(set(pick))]
    return starts

def make_chunks(q_text, a_text):
    q_ids = tokenizer.encode(q_text, add_special_tokens=False)[:CFG.Q_MAX_TOKENS]
    a_ids = tokenizer.encode(a_text, add_special_tokens=False)
    win = CFG.CHUNK_LEN - len(q_ids) - N_SPECIAL
    stride = max(1, int(win * CFG.CHUNK_STRIDE_FRAC))
    return [PAIR_PRE + q_ids + PAIR_MID + a_ids[s:s + win] + PAIR_POST for s in window_starts(len(a_ids), win, stride)]

class PolERoDataset(Dataset):
    def __init__(self, df, is_train=True, chunks=None):
        self.chunks = chunks if chunks is not None else [make_chunks(q, a) for q, a in zip(df['text_q'], df['text_a'])]
        self.is_train = is_train
        if is_train:
            self.y9 = df['evasion_label'].map(evasion2idx).values
            self.y3 = df['clarity_label'].map(clarity2idx).values
            self.sw = df['sample_weight'].values if 'sample_weight' in df.columns else np.ones(len(df))

    def __len__(self):
        return len(self.chunks)

    def __getitem__(self, idx):
        item = {'chunks': self.chunks[idx]}
        if self.is_train:
            item.update(y9=int(self.y9[idx]), y3=int(self.y3[idx]), sw=float(self.sw[idx]))
        return item

def collate_fn(batch):
    flat, chunk_map = [], []
    for i, x in enumerate(batch):
        flat += x['chunks']
        chunk_map += [i] * len(x['chunks'])
    max_len = max(len(c) for c in flat)
    pad = tokenizer.pad_token_id
    out = {'input_ids': torch.tensor([c + [pad] * (max_len - len(c)) for c in flat]),
           'attention_mask': torch.tensor([[1] * len(c) + [0] * (max_len - len(c)) for c in flat]),
           'chunk_map': torch.tensor(chunk_map), 'n': len(batch)}
    if 'y9' in batch[0]:
        out['y9'] = torch.tensor([x['y9'] for x in batch])
        out['y3'] = torch.tensor([x['y3'] for x in batch])
        out['sw'] = torch.tensor([x['sw'] for x in batch], dtype=torch.float)
    return out

class EvasionClassifier(nn.Module):
    def __init__(self, model_name, device):
        super().__init__()
        config = AutoConfig.from_pretrained(model_name)
        config.update({'hidden_dropout_prob': CFG.HIDDEN_DROPOUT, 'attention_probs_dropout_prob': CFG.HIDDEN_DROPOUT})
        self.encoder = AutoModel.from_pretrained(model_name, config=config)
        self.encoder.gradient_checkpointing_enable()
        h = config.hidden_size
        self.attn = nn.Linear(h, 1)
        self.dropouts = nn.ModuleList([nn.Dropout(0.1 * i) for i in range(1, 6)])
        self.fc9 = nn.Linear(2 * h, 9)
        self.fc3 = nn.Linear(2 * h, 3)
        self.device = torch.device(device)
        self.to(self.device)

    def forward(self, input_ids, attention_mask, chunk_map, n):
        mask = attention_mask.to(self.device)
        out = self.encoder(input_ids=input_ids.to(self.device), attention_mask=mask).last_hidden_state
        m = mask.unsqueeze(-1).to(out.dtype)
        mean_pool = (out * m).sum(1) / m.sum(1).clamp(min=1e-9)
        alpha = F.softmax(self.attn(out).squeeze(-1).float().masked_fill(mask == 0, -1e4), dim=1).unsqueeze(-1).to(out.dtype)
        feat = torch.cat([mean_pool, (out * alpha).sum(1)], dim=-1).float()
        idx = chunk_map.to(self.device).unsqueeze(-1).expand_as(feat)
        pooled = torch.full((n, feat.size(1)), float('-inf'), device=self.device).scatter_reduce(0, idx, feat, reduce='amax')
        drops = [dp(pooled) for dp in self.dropouts]
        return sum(self.fc9(d) for d in drops) / len(drops), sum(self.fc3(d) for d in drops) / len(drops)

def param_groups(model):
    groups = []
    for is_head in (False, True):
        named = [(k, p) for k, p in model.named_parameters() if p.requires_grad and k.startswith('encoder.') != is_head]
        lr = CFG.LR * (CFG.HEAD_LR_MULT if is_head else 1.0)
        no_decay = [p for k, p in named if any(s in k for s in ('bias', 'LayerNorm', 'layer_norm'))]
        decay = [p for k, p in named if not any(s in k for s in ('bias', 'LayerNorm', 'layer_norm'))]
        groups += [{'params': decay, 'lr': lr, 'weight_decay': CFG.WEIGHT_DECAY},
                   {'params': no_decay, 'lr': lr, 'weight_decay': 0.0}]
    return [g for g in groups if g['params']]

