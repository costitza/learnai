def resolve_label(row):
    lab = row.get('evasion_label')
    if isinstance(lab, str) and lab in evasion2idx:
        return lab
    votes = [v for v in (row.get(c) for c in ('annotator1', 'annotator2', 'annotator3')) if isinstance(v, str) and v in evasion2idx]
    if not votes:
        return None
    best = max(set(votes), key=votes.count)
    return best if votes.count(best) >= 2 else votes[0]

