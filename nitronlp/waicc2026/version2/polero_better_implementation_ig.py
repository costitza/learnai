def get_cv_score(probs9):
    s1 = f1_score(y_clarity, np.argmax(probs9_to_probs3(probs9), axis=1), average="macro")
    s2 = f1_score(y_evasion, np.argmax(probs9, axis=1), average="macro")
    return s1, s2, 0.5 * (s1 + s2)

s1_raw, s2_raw, best_score = get_cv_score(oof_probs)
print(f"5-Fold BRUT (fără calibrare) -> Sub1: {s1_raw:.4f} | Sub2: {s2_raw:.4f} | Mediu: {best_score:.4f}")

weights = np.ones(9)
for _ in range(3):
    for c in range(9):
        for mult in np.linspace(0.70, 1.65, 20):
            temp_w = weights.copy()
            temp_w[c] = mult
            _, _, sc = get_cv_score(oof_probs * temp_w)
            if sc > best_score:
                best_score = sc
                weights = temp_w

weights_final = 0.85 * weights + 0.15 * np.ones(9)

s1_cal, s2_cal, mean_cal = get_cv_score(oof_probs * weights_final)
