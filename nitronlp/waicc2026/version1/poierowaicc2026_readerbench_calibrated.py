def head_tail_words(text, head_w=210, tail_w=210):
    words = clean_ro(text).split()
    if len(words) <= head_w + tail_w:
        return " ".join(words)
    return " ".join(words[:head_w]) + " [...] " + " ".join(words[-tail_w:])

def shorten_prev_q(text, max_w=45):
    words = clean_ro(text).split()
    if len(words) <= max_w:
        return " ".join(words)
    return " ".join(words[-max_w:])

def format_inputs(df):
    q_inputs, a_inputs = [], []
    for _, row in df.iterrows():
        pres = clean_ro(row["president"])
        ctx = clean_ro(row["context"])

        q_curr = head_tail_words(row["interview_question"], head_w=80, tail_w=60)
        q_prev = shorten_prev_q(row["prev_question"], max_w=35)

        if q_prev:
            q_str = f"[{pres} | {ctx}] Intrebare anterioara: {q_prev} | Intrebare curenta: {q_curr}"
        else:
            q_str = f"[{pres} | {ctx}] Intrebare: {q_curr}"

        a_str = head_tail_words(row["interview_answer"], head_w=170, tail_w=170)
        q_inputs.append(q_str)
        a_inputs.append(a_str)
    return q_inputs, a_inputs

