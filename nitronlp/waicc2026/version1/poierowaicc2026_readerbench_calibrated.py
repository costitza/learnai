def probs9_to_probs3(probs9):
    p_clear = probs9[:, [0]].sum(axis=1)                 # Explicit
    p_ambiv = probs9[:, [1, 2, 3, 4, 5]].sum(axis=1)     # Implicit .. Deflection
    p_nonrep = probs9[:, [6, 7, 8]].sum(axis=1)          # Declining .. Clarification
    return np.stack([p_clear, p_ambiv, p_nonrep], axis=1)

def compute_metrics(eval_pred):
    logits, labels = eval_pred
    probs9 = torch.softmax(torch.tensor(logits), dim=-1).numpy()
    preds9 = np.argmax(probs9, axis=1)
    f1_evasion = f1_score(labels, preds9, average="macro")

    true_clarity = np.array([clarity2id[EVASION_TO_CLARITY[id2label[l]]] for l in labels])
    pred_clarity = np.argmax(probs9_to_probs3(probs9), axis=1)
    f1_clarity = f1_score(true_clarity, pred_clarity, average="macro")

    return {
        "f1_evasion": f1_evasion,
        "f1_clarity": f1_clarity,
        "combined": 0.5 * (f1_evasion + f1_clarity),
    }

