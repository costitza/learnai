INPUT_DIR = "/kaggle/input/datasets/ababeiraul/poiero"


train_df = pd.read_csv(f"{INPUT_DIR}/train_data.csv")
test_df = pd.read_csv(f"{INPUT_DIR}/test_data.csv")

EVASION_TO_CLARITY = {
    "Explicit": "Clear Reply",
    "Implicit": "Ambivalent",
    "General": "Ambivalent",
    "Partial/half-answer": "Ambivalent",
    "Dodging": "Ambivalent",
    "Deflection": "Ambivalent",
    "Declining to answer": "Clear Non-Reply",
    "Claims ignorance": "Clear Non-Reply",
    "Clarification": "Clear Non-Reply",
}

EVASION_LABELS = list(EVASION_TO_CLARITY.keys())
CLARITY_LABELS = ["Clear Reply", "Ambivalent", "Clear Non-Reply"]

label2id = {lbl: i for i, lbl in enumerate(EVASION_LABELS)}
id2label = {i: lbl for i, lbl in enumerate(EVASION_LABELS)}
clarity2id = {lbl: i for i, lbl in enumerate(CLARITY_LABELS)}

def clean_ro(text):
    if pd.isna(text):
        return ""
    return (
        str(text)
        .replace("ţ", "ț").replace("ş", "ș")
        .replace("Ţ", "Ț").replace("Ş", "Ș")
        .strip()
    )


full_df = pd.concat(
    [
        train_df[["datapointID", "url", "question_order", "interview_question"]].assign(is_test=0),
        test_df[["datapointID", "url", "question_order", "interview_question"]].assign(is_test=1),
    ],
    ignore_index=True,
)
full_df = full_df.sort_values(["url", "question_order", "datapointID"]).reset_index(drop=True)

prev_url = full_df["url"].shift(1)
prev_order = full_df["question_order"].shift(1)
prev_q = full_df["interview_question"].shift(1).apply(clean_ro)


is_consecutive = (full_df["url"] == prev_url) & ((full_df["question_order"] - prev_order) == 1)
full_df["prev_question"] = np.where(is_consecutive, prev_q, "")

prev_q_map = dict(zip(full_df["datapointID"], full_df["prev_question"]))
train_df["prev_question"] = train_df["datapointID"].map(prev_q_map)
test_df["prev_question"] = test_df["datapointID"].map(prev_q_map)

print(f"Randuri train q ante consecutiva: {(train_df['prev_question'] != '').sum()} / {len(train_df)}")
