STRIDE = 192
MAX_CHUNKS = 3

def encode_sliding_window(q_text: str, a_text: str):
    q_ids = tokenizer.encode(q_text, add_special_tokens=False)[:160]
    a_ids = tokenizer.encode(a_text, add_special_tokens=False)

    avail_a = CHUNK_LEN - len(q_ids) - 3
    step = max(64, avail_a - (CHUNK_LEN - STRIDE))

    if len(a_ids) == 0:
        a_windows = [[]]
    else:
        a_windows = []
        for start in range(0, len(a_ids), step):
            a_windows.append(a_ids[start : start + avail_a])
            if start + avail_a >= len(a_ids) or len(a_windows) >= MAX_CHUNKS:
                break

    cls_id = tokenizer.cls_token_id
    sep_id = tokenizer.sep_token_id
    pad_id = tokenizer.pad_token_id

    input_ids_list, attn_mask_list = [], []
    for win in a_windows:
        seq = [cls_id] + q_ids + [sep_id] + win + [sep_id]
        mask = [1] * len(seq)
        pad_len = CHUNK_LEN - len(seq)
        if pad_len > 0:
            seq += [pad_id] * pad_len
            mask += [0] * pad_len
        input_ids_list.append(seq)
        attn_mask_list.append(mask)

    num_valid = len(input_ids_list)
    chunk_mask = [1] * num_valid + [0] * (MAX_CHUNKS - num_valid)

    dummy_seq = [cls_id, sep_id] + [pad_id] * (CHUNK_LEN - 2)
    dummy_mask = [1, 1] + [0] * (CHUNK_LEN - 2)
    while len(input_ids_list) < MAX_CHUNKS:
        input_ids_list.append(dummy_seq)
        attn_mask_list.append(dummy_mask)

    return (
        torch.tensor(input_ids_list, dtype=torch.long),
        torch.tensor(attn_mask_list, dtype=torch.long),
        torch.tensor(chunk_mask, dtype=torch.long),
    )


class PolERo6Dataset(Dataset):
    def __init__(self, df: pd.DataFrame, is_test: bool = False):
        self.q_list = df["q_input"].tolist()
        self.a_list = df["a_input"].tolist()
        self.is_test = is_test
        if not is_test:
            self.labels = df["label_6"].values

    def __len__(self):
        return len(self.q_list)

    def __getitem__(self, idx):
        input_ids, attn_mask, chunk_mask = encode_sliding_window(self.q_list[idx], self.a_list[idx])
        item = {"input_ids": input_ids, "attention_mask": attn_mask, "chunk_mask": chunk_mask}
        if not self.is_test:
            item["label"] = torch.tensor(self.labels[idx], dtype=torch.long)
        return item




class Specialist6ClassModel(nn.Module):
    def __init__(self, model_name: str):
        super().__init__()
        self.encoder = AutoModel.from_pretrained(model_name)
        hidden = self.encoder.config.hidden_size

        self.norm = nn.LayerNorm(hidden * 2)
        self.dropout = nn.Dropout(0.25)
        self.head_6 = nn.Linear(hidden * 2, 6)
        self.loss_fn = nn.CrossEntropyLoss(label_smoothing=0.05)

    def forward(self, input_ids, attention_mask, chunk_mask, label=None):
        B, C, L = input_ids.shape
        outputs = self.encoder(
            input_ids=input_ids.view(B * C, L),
            attention_mask=attention_mask.view(B * C, L),
        ).last_hidden_state

        cls_tok = outputs[:, 0, :]
        tok_mask = attention_mask.view(B * C, L, 1).float()
        mean_tok = (outputs * tok_mask).sum(dim=1) / tok_mask.sum(dim=1).clamp(min=1e-6)

        chunk_emb = torch.cat([cls_tok, mean_tok], dim=-1).view(B, C, -1)

        c_mask = chunk_mask.unsqueeze(-1).float()
        doc_repr = (chunk_emb * c_mask).sum(dim=1) / c_mask.sum(dim=1).clamp(min=1.0)
        doc_repr = self.dropout(self.norm(doc_repr))

        logits_6 = self.head_6(doc_repr)
        loss = self.loss_fn(logits_6, label) if label is not None else None
        return loss, logits_6

@torch.no_grad()
def predict_6(model, loader, desc="Eval"):
    model.eval()
    p6_list = []
    for batch in tqdm(loader, desc=desc, leave=False):
        input_ids = batch["input_ids"].to(device)
        attn_mask = batch["attention_mask"].to(device)
        chunk_mask = batch["chunk_mask"].to(device)
        with torch.amp.autocast("cuda", enabled=torch.cuda.is_available()):
            _, logits_6 = model(input_ids, attn_mask, chunk_mask)
        p6_list.append(torch.softmax(logits_6.float(), dim=-1).cpu().numpy())
    return np.vstack(p6_list)

