def build_prompt_pair(row):
    pres = clean_ro(row.get("president", "Unknown"))
    ctx = clean_ro(row.get("context", "Interview"))
    q_curr = clean_ro(row["interview_question"])
    a_curr = clean_ro(row["interview_answer"])

    q_prev = truncate_words(row.get("prev_q", ""), max_words=25, from_end=True)
    a_prev = truncate_words(row.get("prev_a", ""), max_words=25, from_end=True)
    q_next = truncate_words(row.get("next_q", ""), max_words=25, from_end=False)


    parts = [f"[{pres} | {ctx}] Intrebare: {q_curr}"]
    if q_next:
        parts.append(f"Urmatoarea intrebare: {q_next}")
    if q_prev:
        parts.append(f"Intrebare anterioara: {q_prev}")
    if a_prev:
        parts.append(f"Raspuns anterior: {a_prev}")

    return " | ".join(parts), a_curr

