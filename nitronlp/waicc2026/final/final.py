def fit_multipliers(p9, y_ev, y_cl):
    w9 = np.ones(9)
    best_sc = 0.5 * (
        f1_score(y_ev, np.argmax(p9, axis=1), average="macro")
        + f1_score(y_cl, np.argmax(probs9_to_probs3(p9), axis=1), average="macro")
    )
    for _ in range(3):
        for c in range(9):
            for mult in np.linspace(0.65, 1.85, 25):
                tmp = w9.copy()
                tmp[c] = mult
                scaled = p9 * tmp
                sc = 0.5 * (
                    f1_score(y_ev, np.argmax(scaled, axis=1), average="macro")
                    + f1_score(y_cl, np.argmax(probs9_to_probs3(scaled), axis=1), average="macro")
                )
                if sc > best_sc:
                    best_sc, w9 = sc, tmp
    return 0.80 * w9 + 0.20 * np.ones(9)

