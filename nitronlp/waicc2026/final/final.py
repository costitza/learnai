def clean_ro(text):
    if pd.isna(text):
        return ""
    return (
        str(text)
        .replace("ţ", "ț").replace("ş", "ș")
        .replace("Ţ", "Ț").replace("Ş", "Ș")
        .strip()
    )

def truncate_words(text, max_words=25, from_end=False):
    words = clean_ro(text).split()
    if len(words) <= max_words:
        return " ".join(words)
    return " ".join(words[-max_words:]) if from_end else " ".join(words[:max_words])

def add_bidirectional_context(tr_df, te_df):
    full = pd.concat([
        tr_df[["datapointID", "url", "question_order", "interview_question", "interview_answer"]],
        te_df[["datapointID", "url", "question_order", "interview_question", "interview_answer"]],
    ], ignore_index=True).sort_values(["url", "question_order", "datapointID"]).reset_index(drop=True)

    same_prev = (full["url"] == full["url"].shift(1)) & ((full["question_order"] - full["question_order"].shift(1)) <= 2)
    same_next = (full["url"] == full["url"].shift(-1)) & ((full["question_order"].shift(-1) - full["question_order"]) <= 2)

    full["prev_q"] = np.where(same_prev, full["interview_question"].shift(1).fillna(""), "")
    full["prev_a"] = np.where(same_prev, full["interview_answer"].shift(1).fillna(""), "")
    full["next_q"] = np.where(same_next, full["interview_question"].shift(-1).fillna(""), "")

    ctx = full.set_index("datapointID")[["prev_q", "prev_a", "next_q"]]
    for col in ["prev_q", "prev_a", "next_q"]:
        tr_df[col] = tr_df["datapointID"].map(ctx[col])
        te_df[col] = te_df["datapointID"].map(ctx[col])
    return tr_df, te_df

