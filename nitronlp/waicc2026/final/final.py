def combine_gate_and_specialist(p9_gate, p3_gate, p6_spec, tau_high=0.65, tau_low=0.30, alpha_spec=0.55):
    p_nonrep_total = 0.5 * p3_gate[:, 2] + 0.5 * p9_gate[:, 6:9].sum(axis=1)
    p6_from_gate = p9_gate[:, :6] / np.clip(p9_gate[:, :6].sum(axis=1, keepdims=True), 1e-6, None)
    p6_blended = alpha_spec * p6_spec + (1.0 - alpha_spec) * p6_from_gate

    spec_weight = np.clip((tau_high - p_nonrep_total) / max(tau_high - tau_low, 1e-4), 0.0, 1.0)[:, None]

    out_p9 = p9_gate.copy()
    non_rep_mass = out_p9[:, 6:9].sum(axis=1, keepdims=True)
    rem_mass = np.clip(1.0 - non_rep_mass, 0.0, 1.0)
    out_p9[:, :6] = (spec_weight * p6_blended + (1.0 - spec_weight) * p6_from_gate) * rem_mass
    return out_p9

